"""
memory/schema.py
────────────────────────────────────────────────────────────────────────────────
Data schemas for LedgerMind memory operations, normalized memories,
and reflect caching.
"""

from datetime import datetime, timezone
from decimal import Decimal
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from data.models import ApproverDecision, ApproverRole
from data.vendors import get_vendor_slug


class MemoryMode(str, Enum):
    """Execution modes for LedgerMind memory client."""
    LOCAL = "local"
    CLOUD = "cloud"
    OFFLINE = "offline"


class RecalledMemory(BaseModel):
    """
    Normalized representation of a memory returned from Hindsight or offline store.
    Built directly from the verified fields of hindsight_client_api.models.recall_result.RecallResult.
    """
    id: str = Field(description="Unique memory record identifier")
    text: str = Field(description="Narrative or factual memory content")
    type: Optional[str] = Field(default=None, description="Memory type (world, observation, etc.)")
    document_id: Optional[str] = Field(default=None, description="Source document or invoice identifier")
    tags: List[str] = Field(default_factory=list, description="Associated filter tags")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata dictionary")
    score: Optional[float] = Field(default=None, description="Final combined relevance score")
    semantic_score: Optional[float] = Field(default=None, description="Semantic similarity score")
    reranker_score: Optional[float] = Field(default=None, description="Reranker score")
    keyword_score: Optional[float] = Field(default=None, description="BM25 keyword score")
    occurred_start: Optional[datetime] = Field(default=None, description="Start timestamp of event")
    occurred_end: Optional[datetime] = Field(default=None, description="End timestamp of event")
    is_offline_fallback: bool = Field(default=False, description="True if retrieved from offline JSONL fallback")
    bank_id: Optional[str] = Field(default=None, description="Hindsight bank identifier where memory is stored")
    supporting_facts: List[str] = Field(default_factory=list, description="Extracted sub-facts grouped under this verified parent document")
    is_ungrouped: bool = Field(default=False, description="True if fact could not be reliably attributed to a verified parent document")

    @classmethod
    def from_recall_result(cls, r: Any) -> "RecalledMemory":
        """Instantiate cleanly from Hindsight SDK RecallResult object."""
        scores = getattr(r, "scores", None)
        return cls(
            id=str(getattr(r, "id", "")),
            text=str(getattr(r, "text", "") or ""),
            type=getattr(r, "type", None),
            document_id=getattr(r, "document_id", None),
            tags=list(getattr(r, "tags", []) or []),
            metadata=dict(getattr(r, "metadata", {}) or {}),
            score=getattr(scores, "final", None) if scores else None,
            semantic_score=getattr(scores, "semantic", None) if scores else None,
            reranker_score=getattr(scores, "reranker", None) if scores else None,
            keyword_score=getattr(scores, "keyword", None) if scores else None,
            occurred_start=getattr(r, "occurred_start", None),
            occurred_end=getattr(r, "occurred_end", None),
            is_offline_fallback=False,
        )

    @property
    def similarity_score(self) -> Optional[float]:
        """Convenience property alias for semantic score or overall score."""
        return self.semantic_score if self.semantic_score is not None else self.score

    def to_citation_summary(self) -> str:
        """Formatted human-readable citation label for UI and agent reasoning."""
        doc = self.document_id or self.id[:8]
        score_str = f"score: {self.score:.2f}" if self.score is not None else "offline"
        date_str = self.occurred_start.strftime("%Y-%m-%d") if self.occurred_start else "undated"
        return f"[{doc} | {date_str} | {score_str}]"


class RecallQuery(BaseModel):
    """Specification for querying Hindsight agent memory."""
    bank_id: str
    query: str
    tags: Optional[List[str]] = None
    limit: int = 5
    min_score: Optional[float] = None


class ReflectSummary(BaseModel):
    """Cached vendor profile synthesis generated by Hindsight reflect()."""
    vendor_slug: str
    summary: str
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    cached: bool = False


class FeedbackRecord(BaseModel):
    """
    Record of human review, decision, and rationale for an AP exception.
    Retained into persistent memory to reinforce institutional knowledge.
    """
    invoice_number: str
    vendor_name: str
    exception_type: str
    agent_proposal: str
    human_decision: ApproverDecision
    approver_role: ApproverRole = ApproverRole.AP_MANAGER
    human_reason: str
    final_amount_inr: Decimal
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    cited_memory_ids: List[str] = Field(default_factory=list)

    @property
    def document_id(self) -> str:
        """Stable document ID for idempotent feedback retention."""
        return f"feedback-{self.invoice_number}"

    def to_tags(self) -> List[str]:
        slug = get_vendor_slug(self.vendor_name)
        return [
            f"vendor:{slug}",
            f"exception:{self.exception_type.lower()}",
            f"decision:{self.human_decision.value.lower()}",
            f"approver:{self.approver_role.value.lower()}",
            "source:human_feedback",
        ]

    def to_metadata(self) -> Dict[str, str]:
        return {
            "invoice_number": self.invoice_number,
            "vendor_name": self.vendor_name,
            "exception_type": self.exception_type,
            "decision": self.human_decision.value,
            "approver_role": self.approver_role.value,
            "final_amount_inr": f"{self.final_amount_inr:.2f}",
            "agent_proposal": self.agent_proposal,
            "source": "human_feedback",
        }

    def to_narrative(self) -> str:
        date_str = self.timestamp.strftime("%Y-%m-%d")
        return (
            f"On {date_str}, invoice {self.invoice_number} from {self.vendor_name} "
            f"underwent human review for exception {self.exception_type}.\n\n"
            f"Agent proposal was: {self.agent_proposal}\n"
            f"Human decision by {self.approver_role.value}: {self.human_decision.value}.\n"
            f"Reason: {self.human_reason}\n"
            f"Final financial resolution: ₹{self.final_amount_inr:,.2f}."
        )

